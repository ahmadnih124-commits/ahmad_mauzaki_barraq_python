# A.12.1 Pengenalan list

# contoh list
list_1 = [10, 70, 20]

# list dengan deklarasi element secara vertikal
list_2 = [
    'ab',
    'cd',
    'hi',
    'ca'
]

# list dengan element berisi bermacam-macam tipe data
list_3 = [3.14, 'hello python', True, False]

# list kosong
list_4 = []

print("list_1:", list_1)
print("list_2:", list_2)
print("list_3:", list_3)
print("list_4:", list_4)
